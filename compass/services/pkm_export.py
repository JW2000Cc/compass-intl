"""PKM-style markdown export — one note per entity, alongside SQLite.

Why: data sovereignty. SQLite is the operational store (queries fast),
but markdown files are the *user-readable, user-portable* form. If Compass
disappears tomorrow, your contacts and company notes still live as plain
text you can open in Obsidian / VS Code / cat / git.

Layout (under SETTINGS.data_dir):
    data/contacts/<slug>.md      one per Connection
    data/companies/<slug>.md     one per company you have ≥1 connection at
    data/jobs/<slug>.md          one per Job (lightweight summary; full data still in DB)

Sync direction: **DB → markdown**. We do NOT parse markdown back into the DB
in this version (would require conflict resolution; out of scope).
The user can edit markdown for THEIR notes — those persist as long as we
don't overwrite their hand-written sections.

Hand-edit-safe strategy:
    Each .md has two parts:
      1. SYSTEM section (between BEGIN/END markers) — overwritten on each export
      2. USER section (everything else) — preserved on re-export

This means user notes in their own paragraph survive re-import, only the
auto-generated frontmatter + system block changes.

Toggle: COMPASS_PKM_EXPORT env var or settings.pkm_export_enabled. Off by
default to avoid surprising users who don't want files written.
"""
from __future__ import annotations

import logging
import re
from datetime import datetime, timezone
from pathlib import Path
from typing import Optional

from sqlalchemy import select
from sqlalchemy.orm import Session

from ..models import Connection, Job, OutreachAttempt
from .connections import companies_with_connections, find_connections_at

log = logging.getLogger(__name__)

_BEGIN_MARKER = "<!-- COMPASS:SYSTEM:BEGIN -->"
_END_MARKER = "<!-- COMPASS:SYSTEM:END -->"

_SLUG_RE = re.compile(r"[^\w一-鿿\-]+", re.UNICODE)


def _slugify(s: str, max_len: int = 80) -> str:
    """ASCII-safe filename slug. Preserves CJK chars; replaces other punctuation."""
    s = (s or "").strip()
    s = _SLUG_RE.sub("-", s)
    s = re.sub(r"-+", "-", s).strip("-").lower()
    return s[:max_len] or "untitled"


def _settings_data_dir() -> Path:
    try:
        from flask import current_app
        return current_app.config["SETTINGS"].data_dir
    except Exception:
        return Path("data")


def _pkm_enabled() -> bool:
    """PKM export is opt-in. Returns True if env or settings flag is on."""
    import os
    if os.environ.get("COMPASS_PKM_EXPORT", "").lower() in ("1", "true", "yes", "on"):
        return True
    try:
        from flask import current_app
        return bool(getattr(current_app.config["SETTINGS"], "pkm_export_enabled", False))
    except Exception:
        return False


# ─────────────────────────────────────────────────────────
# Markdown sectioning — preserve user-written content
# ─────────────────────────────────────────────────────────


def _split_existing(path: Path) -> tuple[str, str]:
    """Split existing .md into (before_user_section, user_notes_section).

    Strategy: everything BEFORE the first SYSTEM:BEGIN marker is preserved as
    'pre' (rare — usually empty). The SYSTEM block itself is replaced. Anything
    AFTER SYSTEM:END is the user's notes — preserved as-is.

    If file doesn't exist: return ("", "").
    If no markers: treat ENTIRE existing content as user_notes (user's manual
    file that we're now supplementing).
    """
    if not path.exists():
        return ("", "")
    text = path.read_text(encoding="utf-8")
    if _BEGIN_MARKER not in text:
        return ("", text.strip() + "\n" if text.strip() else "")
    pre, _, rest = text.partition(_BEGIN_MARKER)
    if _END_MARKER in rest:
        _, _, user_notes = rest.partition(_END_MARKER)
        return (pre, user_notes.lstrip("\n"))
    # Malformed — has BEGIN but no END. Conservative: treat all post-BEGIN as user.
    return (pre, "\n" + rest.strip() + "\n")


def _wrap_system_block(body: str) -> str:
    """Wrap autogenerated body between BEGIN/END markers."""
    return f"{_BEGIN_MARKER}\n{body.rstrip()}\n{_END_MARKER}\n"


def _write_md(path: Path, system_body: str) -> None:
    """Write or update a .md file, preserving any user-edited section."""
    path.parent.mkdir(parents=True, exist_ok=True)
    pre, user_notes = _split_existing(path)
    parts: list[str] = []
    if pre.strip():
        parts.append(pre.rstrip() + "\n\n")
    parts.append(_wrap_system_block(system_body))
    if user_notes.strip():
        parts.append("\n" + user_notes.rstrip() + "\n")
    else:
        # Seed a placeholder for user notes
        parts.append("\n## Your notes\n\n_(your hand-written notes go here — "
                     "Compass will not overwrite this section)_\n")
    tmp = path.with_suffix(path.suffix + ".tmp")
    tmp.write_text("".join(parts), encoding="utf-8")
    tmp.replace(path)


