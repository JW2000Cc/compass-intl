def _render_connection_body(c: Connection) -> str:
    """Frontmatter + summary table for one Connection."""
    fm_lines = ["---"]
    fm_lines.append(f"name: \"{c.name}\"")
    if c.current_company:
        fm_lines.append(f"company: \"{c.current_company}\"")
    if c.current_title:
        fm_lines.append(f"title: \"{c.current_title}\"")
    if c.linkedin_url:
        fm_lines.append(f"linkedin: \"{c.linkedin_url}\"")
    if c.email:
        fm_lines.append(f"email: \"{c.email}\"")
    fm_lines.append(f"source: \"{c.source}\"")
    if c.connected_at:
        fm_lines.append(f"connected_at: {c.connected_at:%Y-%m-%d}")
    if c.last_contacted_at:
        fm_lines.append(f"last_contacted: {c.last_contacted_at:%Y-%m-%d}")
    fm_lines.append(f"compass_id: {c.id}")
    fm_lines.append(f"updated: {datetime.now(timezone.utc):%Y-%m-%d %H:%M}")
    fm_lines.append("---")

    body = ["", f"# {c.name}", ""]
    if c.current_title or c.current_company:
        body.append(f"**{c.current_title or '—'}**" + (f" @ {c.current_company}" if c.current_company else ""))
    if c.linkedin_url:
        body.append(f"\n[LinkedIn]({c.linkedin_url})")
    return "\n".join(fm_lines + body)


def _render_company_body(company_name: str, connections_at: list[Connection]) -> str:
    fm_lines = ["---"]
    fm_lines.append(f"company: \"{company_name}\"")
    fm_lines.append(f"connection_count: {len(connections_at)}")
    fm_lines.append(f"updated: {datetime.now(timezone.utc):%Y-%m-%d %H:%M}")
    fm_lines.append("---")

    body = ["", f"# {company_name}", ""]
    body.append(f"**{len(connections_at)} 个连接** 在此公司")
    body.append("")
    body.append("## 你认识的人")
    body.append("")
    for c in connections_at:
        title = c.current_title or "—"
        link = c.linkedin_url or ""
        line = f"- **{c.name}** · {title}"
        if link:
            line += f" · [LinkedIn]({link})"
        if c.connected_at:
            line += f" · 加为连接 {c.connected_at:%Y-%m}"
        body.append(line)
    return "\n".join(fm_lines + body)


def _render_job_body(job: Job, outreach_count: int) -> str:
    fm_lines = ["---"]
    fm_lines.append(f"title: \"{job.title}\"")
    if job.company:
        fm_lines.append(f"company: \"{job.company}\"")
    if job.location:
        fm_lines.append(f"location: \"{job.location}\"")
    fm_lines.append(f"status: {job.status}")
    if job.is_remote:
        fm_lines.append("remote: true")
    if job.salary_min:
        fm_lines.append(f"salary_min: {job.salary_min}")
        if job.salary_currency:
            fm_lines.append(f"salary_currency: {job.salary_currency}")
    if job.link:
        fm_lines.append(f"jd_link: \"{job.link}\"")
    fm_lines.append(f"compass_id: {job.id}")
    fm_lines.append(f"updated: {datetime.now(timezone.utc):%Y-%m-%d %H:%M}")
    fm_lines.append("---")

    body = ["", f"# {job.title}", ""]
    body.append(f"**{job.company or '—'}** · {job.location or '—'} · status: `{job.status}`")
    if outreach_count:
        body.append(f"\n📜 已对此 job 发出 **{outreach_count}** 次 outreach")
    if job.link:
        body.append(f"\n[原 JD]({job.link})")
    return "\n".join(fm_lines + body)


