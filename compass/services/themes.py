"""Resume theme registry — built-in + user-uploaded.

Themes are Jinja templates that receive a JSON Resume `r` object as context.
Built-ins live in package; user uploads live in `<data>/templates/`.

Variable convention (what users use in their templates):

    {{ r.basics.name }}              # str
    {{ r.basics.email }}             # str
    {{ r.basics.phone }}             # str
    {{ r.basics.location.address }}  # str
    {{ r.basics.summary }}           # str

    {% for w in r.work %}            # list
        {{ w.name }}                 # company
        {{ w.position }}
        {{ w.startDate }} – {{ w.endDate }}
        {% for h in w.highlights %}{{ h }}{% endfor %}
    {% endfor %}

    {% for e in r.education %} … {% endfor %}
    {% for s in r.skills %}    … {% endfor %}
    {% for p in r.projects %}  … {% endfor %}
    {% for l in r.languages %} … {% endfor %}

Built-in themes use Jinja's package loader so they pick up filters like
`local_dt` if needed. User themes use a sandboxed-string environment for
safety, but since Compass is local-only we don't need full sandboxing.
"""
