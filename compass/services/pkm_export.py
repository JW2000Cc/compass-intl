# Public API
# ─────────────────────────────────────────────────────────


def export_connection(c: Connection) -> Optional[Path]:
    """Write/update one Connection's .md. Returns the file path or None if disabled."""
    if not _pkm_enabled():
        return None
    if not c.active:
        return None
    base = _settings_data_dir() / "contacts"
    name_slug = _slugify(c.name) or "unnamed"
    short_id = c.id[:6] if c.id else ""
    fname = f"{name_slug}-{short_id}.md"
    path = base / fname
    _write_md(path, _render_connection_body(c))
    return path


def export_company(session: Session, company_name: str) -> Optional[Path]:
    if not _pkm_enabled():
        return None
    connections = find_connections_at(session, company_name, limit=200)
    if not connections:
        return None
    base = _settings_data_dir() / "companies"
    fname = f"{_slugify(company_name)}.md"
    path = base / fname
    _write_md(path, _render_company_body(company_name, connections))
    return path


def export_job(session: Session, job: Job) -> Optional[Path]:
    if not _pkm_enabled():
        return None
    base = _settings_data_dir() / "jobs"
    title_slug = _slugify(job.title or "untitled")
    fname = f"{title_slug}-{job.id[:6]}.md"
    outreach_count = session.execute(
        select(OutreachAttempt).where(OutreachAttempt.job_id == job.id)
    ).scalars().all().__len__()
    path = base / fname
    _write_md(path, _render_job_body(job, outreach_count))
    return path


def sync_all(session: Session) -> dict:
    """One-shot full sync. Useful after CSV import or migration. Returns counts."""
    if not _pkm_enabled():
        return {"enabled": False}
    counts = {"connections": 0, "companies": 0, "jobs": 0}

    for c in session.execute(select(Connection).where(Connection.active.is_(True))).scalars():
        if export_connection(c):
            counts["connections"] += 1

    for company, _cnt in companies_with_connections(session, limit=200):
        if export_company(session, company):
            counts["companies"] += 1

    for j in session.execute(
        select(Job).where(Job.deleted.is_(False))
    ).scalars().all()[:200]:  # cap at 200 to keep first sync fast
        if export_job(session, j):
            counts["jobs"] += 1

    return {"enabled": True, **counts}
